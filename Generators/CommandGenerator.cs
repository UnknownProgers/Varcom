using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Varcom.Generators;

[Generator]
public sealed class CommandGenerator : IIncrementalGenerator
{
	private static readonly DiagnosticDescriptor Invalid = new(
		"VARCOM001",
		"Unsupported Varcom declaration",
		"{0}",
		"Varcom",
		DiagnosticSeverity.Error,
		true);

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var commands = Attributed(context, "Varcom.CmdAttribute");
		var variables = Attributed(context, "Varcom.VarAttribute");
		var handlers = Attributed(context, "Varcom.CmdHandlerAttribute");
		var modules = Attributed(context, "Varcom.CmdModuleAttribute");
		var declarations = commands.Combine(variables).Combine(handlers).Select((data, _) =>
			data.Left.Left.Concat(data.Left.Right).Concat(data.Right).Distinct(SymbolEqualityComparer.Default).ToArray());
		var input = declarations.Combine(modules).Combine(context.CompilationProvider);
		context.RegisterSourceOutput(input, (output, data) =>
			Generate(output, data.Left.Left, data.Left.Right, data.Right));
	}

	private static IncrementalValueProvider<ImmutableArray<ISymbol>> Attributed(IncrementalGeneratorInitializationContext context,
		string name) =>
		context.SyntaxProvider.ForAttributeWithMetadataName(name, static (_, _) => true,
			static (c, _) => c.TargetSymbol).Collect();

	private static void Generate(SourceProductionContext context, ISymbol[] symbols, ImmutableArray<ISymbol> modules,
		Compilation compilation)
	{
		var assembly = compilation.AssemblyName ?? "Application";
		var registeredOwners = new List<INamedTypeSymbol>();
		var metadata = new CommandMetadataGenerator(assembly);
		foreach (var command in symbols.OfType<INamedTypeSymbol>().Where(t => Attribute(t, "Cmd") != null)
			         .OrderBy(Type, StringComparer.Ordinal))
		{
			if (CommandParameters(context, command, out var parameters))
				metadata.Command(command, Info(Attribute(command, "Cmd")!, parameters, true));
		}

		var owners = symbols
			.Where(s => s is IMethodSymbol or IPropertySymbol or IFieldSymbol || Attribute(s, "CmdHandler") != null)
			.Select(s => s is INamedTypeSymbol t ? t : s.ContainingType)
			.Distinct(SymbolEqualityComparer.Default).OfType<INamedTypeSymbol>()
			.OrderBy(Type, StringComparer.Ordinal);
		var sb = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
		sb.Append("namespace Varcom.Generated.").Append(Safe(assembly)).AppendLine(";");
		sb.AppendLine("public static class CommandRegistration\n{");
		foreach (var owner in owners)
		{
			if (owner.TypeKind != TypeKind.Class || owner.DeclaredAccessibility != Accessibility.Public || owner.ContainingType != null ||
			    owner.IsGenericType || owner.IsStatic)
			{
				Report(context, owner, "Varcom owners must be public, non-static, non-generic top-level classes.");
				continue;
			}

			var registrations = new List<string>();
			var valid = AddHandler(context, owner, registrations, metadata);
			foreach (var member in owner.GetMembers())
			{
				if (member is IMethodSymbol method && Attribute(member, "Cmd") is { } cmd)
					valid &= AddMethod(context, method, cmd, registrations, metadata);
				if (Attribute(member, "Var") is { } variable)
					valid &= AddVariable(context, member, variable, registrations, metadata);
			}

			if (!valid || registrations.Count == 0)
				continue;

			registeredOwners.Add(owner);
			sb.Append("    public static global::System.IDisposable Register(this global::Varcom.CommandRegistry registry, ")
				.Append(Type(owner)).AppendLine(" owner)\n    {");
			sb.AppendLine(
				"        global::System.ArgumentNullException.ThrowIfNull(registry);\n        global::System.ArgumentNullException.ThrowIfNull(owner);");
			sb.AppendLine("        return global::Varcom.RegistrationGroup.Create(");
			sb.Append(string.Join(",\n", registrations.Select(r => "            () => " + r)));
			sb.AppendLine(");\n    }");
		}

		sb.AppendLine("}");
		context.AddSource("Varcom.Registrations.g.cs", sb.ToString());
		metadata.Emit(context, compilation);
		CommandModuleGenerator.Generate(context, compilation, modules.OfType<INamedTypeSymbol>().ToArray(), registeredOwners);
	}

	private static bool AddHandler(SourceProductionContext context, INamedTypeSymbol owner, List<string> registrations,
		CommandMetadataGenerator metadata)
	{
		var attr = Attribute(owner, "CmdHandler");
		if (attr == null)
			return true;

		if (attr.ConstructorArguments.FirstOrDefault().Value is not INamedTypeSymbol command ||
		    Attribute(command, "Cmd") is not { } declaration)
		{
			Report(context, owner, "CmdHandler must reference a command struct marked with Cmd.");
			return false;
		}

		if (!owner.AllInterfaces.Any(i =>
			    i.OriginalDefinition.ToDisplayString() == "Varcom.Contracts.ICommandHandler<TCommand>" &&
			    SymbolEqualityComparer.Default.Equals(i.TypeArguments[0], command)))
		{
			Report(context, owner, "Handler must implement ICommandHandler<T> for its declared command.");
			return false;
		}

		if (!CommandParameters(context, command, out var parameters)) return false;
		metadata.Command(command, Info(declaration, parameters, true));
		var info = Info(declaration, parameters, false);
		registrations.Add(
			$"registry.Register<{Type(command)}>({info}, args => new {Type(command)}({Arguments(parameters)}), owner)");
		return true;
	}

	private static bool CommandParameters(SourceProductionContext context, INamedTypeSymbol command, out IParameterSymbol[] parameters)
	{
		parameters = Array.Empty<IParameterSymbol>();

		if (command.TypeKind != TypeKind.Struct || command.IsGenericType || command.ContainingType != null ||
		    command.DeclaredAccessibility != Accessibility.Public ||
		    !command.AllInterfaces.Any(i => i.ToDisplayString() == "Varcom.Contracts.ICommand"))
		{
			Report(context, command, "Commands must be public, non-generic top-level structs implementing ICommand.");
			return false;
		}

		var ctors = command.InstanceConstructors
			.Where(c => c.DeclaredAccessibility == Accessibility.Public && !c.IsImplicitlyDeclared)
			.ToArray();

		if (ctors.Length == 0)
			parameters = Array.Empty<IParameterSymbol>();
		else if (ctors.Length == 1)
			parameters = ctors[0].Parameters.ToArray();
		else
		{
			Report(context, command, "Command needs one unambiguous public constructor.");
			return false;
		}

		if (!Parameters(context, command, parameters) || !Name(context, command, Attribute(command, "Cmd")!))
			return false;
		return true;
	}

	private static bool AddMethod(SourceProductionContext context, IMethodSymbol method, AttributeData attr, List<string> registrations,
		CommandMetadataGenerator metadata)
	{
		if (method.DeclaredAccessibility != Accessibility.Public || method.IsGenericMethod || method.IsAsync ||
		    method.MethodKind != MethodKind.Ordinary || method.ReturnsByRef || method.ReturnsByRefReadonly ||
		    !method.ReturnsVoid && method.ReturnType.ToDisplayString() != "Varcom.Contracts.CommandResult")
		{
			Report(context, method, "Cmd methods must be public synchronous non-generic methods returning void or CommandResult.");
			return false;
		}

		var parameters = method.Parameters.ToArray();
		if (!Parameters(context, method, parameters) || !Name(context, method, attr))
			return false;
		var target = method.IsStatic ? Type(method.ContainingType) : "owner";
		var call = $"{target}.@{method.Name}({Arguments(parameters)})";
		var body = method.ReturnsVoid ? $"{{ {call}; return global::Varcom.Contracts.CommandResult.Ok(); }}" : call;
		metadata.Command(method, Info(attr, parameters, true));
		var info = Info(attr, parameters, false);
		registrations.Add($"registry.RegisterMethod({info}, args => {body})");
		return true;
	}

	private static bool AddVariable(SourceProductionContext context, ISymbol member, AttributeData attr, List<string> registrations,
		CommandMetadataGenerator metadata)
	{
		ITypeSymbol type;
		bool readOnly;
		if (member is IPropertySymbol p
		    && p.GetMethod?.DeclaredAccessibility == Accessibility.Public
		    && !p.IsIndexer
		    && !p.ReturnsByRef
		    && !p.ReturnsByRefReadonly)
		{
			type = p.Type;
			readOnly = p.SetMethod?.DeclaredAccessibility != Accessibility.Public || p.SetMethod.IsInitOnly;
		}
		else if (member is IFieldSymbol f && f.DeclaredAccessibility == Accessibility.Public)
		{
			type = f.Type;
			readOnly = f.IsReadOnly || f.IsConst;
		}
		else
		{
			Report(context, member, "Var needs a public readable property or field.");
			return false;
		}

		if (member.IsStatic || !Supported(type))
		{
			Report(context, member, "Var needs a supported instance value: CmdString, bool, int, float, double or enum.");
			return false;
		}

		if (!Name(context, member, attr))
			return false;

		var access = "owner.@" + member.Name;
		var setter = readOnly ? "" : $", value => {{ {access} = value; return global::Varcom.Contracts.CommandResult.Ok(); }}";
		var description = Text(attr, 1);
		var variable =
			$"new global::Varcom.Contracts.VariableInfo({Text(attr, 0)}, {description}, typeof({Type(type)}), {readOnly.ToString().ToLowerInvariant()})";
		var info =
			$"new global::Varcom.Contracts.CommandInfo({Text(attr, 0)}, {description}, new global::Varcom.Contracts.CommandParameter[] {{ new global::Varcom.Contracts.CommandParameter(\"value\", typeof({Type(type)}), true) }})";
		metadata.Variable(member, info, variable);
		var variableInfo =
			$"new global::Varcom.Contracts.VariableInfo({Text(attr, 0)}, {Literal("")}, typeof({Type(type)}), {readOnly.ToString().ToLowerInvariant()})";
		registrations.Add($"registry.RegisterVariable<{Type(type)}>({variableInfo}, () => {access}{setter})");
		return true;
	}

	private static bool Parameters(SourceProductionContext context, ISymbol owner, IParameterSymbol[] parameters)
	{
		if (parameters.Any(p => !Supported(p.Type) || p.RefKind != RefKind.None || p.IsParams))
		{
			Report(context, owner,
				"Supported arguments are CmdString, bool, int, float, double and enum; ref/out/in and params are not supported.");
			return false;
		}

		return true;
	}

	private static bool Supported(ITypeSymbol type) => type.TypeKind == TypeKind.Enum ||
		type.ToDisplayString() == "Varcom.Contracts.CmdString" || type.SpecialType is
			SpecialType.System_Boolean or SpecialType.System_Int32
			or SpecialType.System_Single
			or SpecialType.System_Double;

	private static string Info(AttributeData attr, IParameterSymbol[] parameters, bool metadata) =>
		$"new global::Varcom.Contracts.CommandInfo("
		+ $"{Text(attr, 0)}, {(metadata ? Text(attr, 1) : Literal(""))}, new global::Varcom.Contracts.CommandParameter[] "
		+ $"{{ {string.Join(", ", parameters.Select(p => Parameter(p, metadata)))} }})";

	private static string Parameter(IParameterSymbol parameter, bool metadata)
	{
		var arguments = $"{parameter.HasExplicitDefaultValue.ToString().ToLowerInvariant()}, {Default(parameter)}";
		return metadata
			? $"new global::Varcom.Contracts.CommandParameter({Literal(parameter.Name)}, typeof({Type(parameter.Type)}), {arguments})"
			: $"global::Varcom.Contracts.CommandParameter.Create<{Type(parameter.Type)}>({Literal(parameter.Name)}, {arguments})";
	}

	private static string Arguments(IParameterSymbol[] parameters) =>
		string.Join(", ", parameters.Select((p, i) => $"args.Get<{Type(p.Type)}>({i})"));

	private static string Default(IParameterSymbol parameter)
	{
		if (!parameter.HasExplicitDefaultValue || parameter.ExplicitDefaultValue == null)
			return "null";
		var value = parameter.ExplicitDefaultValue;
		if (value is string s)
			return Literal(s);
		if (value is bool b)
			return b ? "true" : "false";
		if (value is float f)
			return float.IsNaN(f) ? "float.NaN" :
				float.IsPositiveInfinity(f) ? "float.PositiveInfinity" :
				float.IsNegativeInfinity(f) ? "float.NegativeInfinity" : f.ToString("R", CultureInfo.InvariantCulture) + "F";
		if (value is double d)
			return double.IsNaN(d) ? "double.NaN" :
				double.IsPositiveInfinity(d) ? "double.PositiveInfinity" :
				double.IsNegativeInfinity(d) ? "double.NegativeInfinity" : d.ToString("R", CultureInfo.InvariantCulture) + "D";
		var literal = Convert.ToString(value, CultureInfo.InvariantCulture) ?? "null";
		return parameter.Type.TypeKind == TypeKind.Enum ? $"({Type(parameter.Type)})({literal})" : literal;
	}

	private static AttributeData? Attribute(ISymbol symbol, string name) => symbol.GetAttributes()
		.FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == "Varcom." + name + "Attribute");

	private static string Type(ITypeSymbol symbol) => symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
	private static string Literal(string text) => SymbolDisplay.FormatLiteral(text, true);

	private static string Text(AttributeData attr, int index) =>
		Literal(attr.ConstructorArguments.Length > index ? attr.ConstructorArguments[index].Value as string ?? "" : "");

	internal static string Safe(string text) => "Assembly_" + new string(text.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray());

	private static bool Name(SourceProductionContext context, ISymbol symbol, AttributeData attr)
	{
		var name = attr.ConstructorArguments.FirstOrDefault().Value as string;
		var start = !string.IsNullOrEmpty(name) && (name![0] == '+' || name[0] == '-') ? 1 : 0;
		if (name == null || name.Length <= start || !AsciiLetter(name[start]) ||
		    name.Skip(start + 1).Any(c => !AsciiLetter(c) && !(c >= '0' && c <= '9') && c != '_' && c != '.'))
		{
			Report(context, symbol,
				"Command names must use ASCII letters, digits, underscore or dot, starting with a letter (optionally prefixed by + or -).");
			return false;
		}

		return true;
	}

	private static bool AsciiLetter(char c) => c >= 'A' && c <= 'Z' || c >= 'a' && c <= 'z';

	internal static void Report(SourceProductionContext context, ISymbol symbol, string message) =>
		context.ReportDiagnostic(Diagnostic.Create(Invalid, symbol.Locations.FirstOrDefault(), message));
}
