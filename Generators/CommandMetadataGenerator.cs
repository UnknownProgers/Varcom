using System.Collections.Generic;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Varcom.Generators;

internal sealed class CommandMetadataGenerator(string assembly)
{
	private readonly Dictionary<ISymbol, string> _entries = new(SymbolEqualityComparer.Default);
	private readonly string _namespace = "Varcom.Generated." + CommandGenerator.Safe(assembly);

	internal void Command(ISymbol symbol, string info) =>
		Add(symbol, info, "null");

	internal void Variable(ISymbol symbol, string info, string variable) =>
		Add(symbol, info, variable);

	private void Add(ISymbol symbol, string info, string variable)
	{
		if (_entries.ContainsKey(symbol)) return;
		var owner = symbol is INamedTypeSymbol type ? type : symbol.ContainingType;
		var memberId = 0;
		if (symbol is not INamedTypeSymbol)
		{
			foreach (var member in owner.GetMembers())
			{
				memberId++;
				if (SymbolEqualityComparer.Default.Equals(member, symbol)) break;
			}
		}

		var ownerType = $"typeof({owner.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)})";
		var formattedInfo = FormatExpression(SyntaxFactory.ParseExpression(info), 4);
		var formattedVariable = FormatExpression(SyntaxFactory.ParseExpression(variable), 4);
		_entries.Add(symbol, $$"""
		                               if (!registry.ContainsMetadata({{ownerType}}, {{memberId}}))
		                               {
		                                   registry.AddMetadata(
		                                       {{ownerType}},
		                                       {{memberId}},
		                                       {{formattedInfo}},
		                                       {{formattedVariable}});
		                               }
		                       """);
	}

	private static string FormatExpression(ExpressionSyntax expression, int depth)
	{
		switch (expression)
		{
			case ObjectCreationExpressionSyntax { ArgumentList: { } arguments } creation:
				return $"new {creation.Type}" + FormatArguments(arguments, depth);
			case ArrayCreationExpressionSyntax { Initializer: { } initializer } array:
				if (initializer.Expressions.Count == 0) return $"new {array.Type} {{ }}";
				var items = string.Join(",\n", initializer.Expressions.Select(item =>
					Indent(depth + 1) + FormatExpression(item, depth + 1)));
				return $"new {array.Type}\n{Indent(depth)}{{\n{items}\n{Indent(depth)}}}";
			default:
				return expression.ToString();
		}
	}

	private static string FormatArguments(ArgumentListSyntax arguments, int depth)
	{
		if (arguments.Arguments.Count == 0) return "()";
		var items = string.Join(",\n", arguments.Arguments.Select(argument =>
			Indent(depth + 1) + FormatExpression(argument.Expression, depth + 1)));
		return $"(\n{items}\n{Indent(depth)})";
	}

	private static string Indent(int depth) => new(' ', depth * 4);

	internal void Emit(SourceProductionContext context, Compilation compilation)
	{
		if (_entries.Count == 0) return;
		if (compilation.GetTypeByMetadataName(_namespace + ".CommandMetadata") is { } conflict)
		{
			CommandGenerator.Report(context, conflict, "CommandMetadata is reserved for generated metadata registration.");
			return;
		}

		var declarations = string.Join("\n\n", _entries.Values);
		var source = $$"""
		               // <auto-generated/>
		               #nullable enable
		               namespace {{_namespace}};

		               public static class CommandMetadata
		               {
		                   public static void GenerateMetadata(this global::Varcom.CommandRegistry registry)
		                   {
		               {{declarations}}
		                   }
		               }
		               """;
		context.AddSource("Varcom.Metadata.g.cs", source);
	}
}
